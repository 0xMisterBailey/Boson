#!/usr/bin/env python3
"""docs/NODES.md from the node pack itself: every node's name, what it does (its docstring and DESCRIPTION), its inputs
and outputs. Run after changing a node; the test suite fails while the page is stale.

  python3 tools/node_docs.py           # rewrite docs/NODES.md
  python3 tools/node_docs.py --check   # exit 1 if docs/NODES.md is out of date
"""
import argparse, pathlib, re, sys, types

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "NODES.md"
GROUPS = {"boson": "Studio and loop", "boson/scene": "Scene"}


def load_nodes():
    """boson.nodes outside ComfyUI: the one ComfyUI symbol it imports at load (ExecutionBlocker) stubbed."""
    if "comfy_execution.graph_utils" not in sys.modules:
        stub = types.ModuleType("comfy_execution.graph_utils")
        stub.ExecutionBlocker = type("ExecutionBlocker", (), {})
        sys.modules.setdefault("comfy_execution", types.ModuleType("comfy_execution"))
        sys.modules["comfy_execution.graph_utils"] = stub
    sys.path.insert(0, str(ROOT))
    from boson import nodes
    return nodes.NODE_CLASS_MAPPINGS, nodes.NODE_DISPLAY_NAME_MAPPINGS


def words(s):
    """One paragraph, without the design-doc cross-references (SPEC.md is not shipped)."""
    s = re.sub(r";\s*SPEC v3 §[\d.]+, I\d+", "", " ".join((s or "").split()))
    return re.sub(r"\s*\((?:SPEC[^)]*|I\d+|round \d+)\)", "", s)


def inputs(cls):
    spec = cls.INPUT_TYPES()
    out = []
    for kind in ("required", "optional"):
        for name, v in spec.get(kind, {}).items():
            t = v[0] if isinstance(v, tuple) else v
            t = "choice" if isinstance(t, (list, tuple)) else str(t)
            out.append(f"`{name}` {t}" + (" (optional)" if kind == "optional" else ""))
    return out


def render():
    classes, names = load_nodes()
    lines = ["# Boson nodes", "",
             "Generated by `tools/node_docs.py` from the node pack (`boson/`); do not edit by hand. Every node sits",
             "under the `boson` category in ComfyUI's node library. `STUDIO` and `SCENE` are git repos in flight:",
             "a node that changes one commits, and re-queuing a node that already ran commits nothing.", ""]
    for cat, title in GROUPS.items():
        keys = [k for k, c in classes.items() if getattr(c, "CATEGORY", "boson") == cat]
        lines += [f"## {title} ({len(keys)})", ""]
        for k in keys:
            c = classes[k]
            outs = getattr(c, "RETURN_TYPES", ())
            rn = getattr(c, "RETURN_NAMES", None) or [t.lower() for t in outs]
            lines += [f"### {names.get(k, k)} (`{k}`)", ""]
            for text in (words(c.__doc__), words(getattr(c, "DESCRIPTION", ""))):
                if text:
                    lines += [text, ""]
            lines += ["- In: " + (", ".join(inputs(c)) or "none"),
                      "- Out: " + (", ".join(f"`{n}` {t}" for n, t in zip(rn, outs)) or "none (an output node)"), ""]
    return "\n".join(lines).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/NODES.md is out of date")
    a = ap.parse_args()
    text = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("docs/NODES.md is current" if ok else "docs/NODES.md is stale: python3 tools/node_docs.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10) + '### ')} nodes)")


if __name__ == "__main__":
    main()
